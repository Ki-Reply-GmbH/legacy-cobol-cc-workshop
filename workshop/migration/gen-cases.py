#!/usr/bin/env python3
"""Generate workshop/migration/maps-cases.txt: the inputs for the maps golden-master check.

Deterministic (fixed seed), so the file can be regenerated byte for byte:
    python3 workshop/migration/gen-cases.py

One case per line, fixed columns, module id first:
  01|<enc 1><pass 4><name 32>       maps01 (password / name encoder; not called by anything today)
  04|<date 10>|<bin, sign + 10 digits>   maps04 (date check/convert; 87 call sites)
  09|<customer 6><digit 1><reply 1>  maps09 (check digit; 7 call sites)

The inputs are chosen from reading the COBOL, not at random alone: leap years,
range edges, odd delimiters, garbage bytes the original doesn't validate, and
sequences that expose maps01's output buffers surviving between calls. What the
right answer is for each one is decided later by running the ORIGINAL COBOL.
"""
import os, random

HERE = os.path.dirname(os.path.abspath(__file__))
rnd = random.Random(20261006)
PRINTABLE = [chr(c) for c in range(0x20, 0x7F) if chr(c) != "|"]
ALPHA37 = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-"
cases = []


def b(n):
    return ("%+011d" % n)


# ---- maps09: customer check digit (same inputs as the benchmark's visible set) -----------
def suma(nos):
    if any(c not in ALPHA37 for c in nos):
        return 0
    return sum((ALPHA37.index(c) + 1) * (8 - i) for i, c in enumerate(nos, 1))


m09 = []
want = {0: 0, 1: 0}                       # check value 11 and 10 are stored as 1 and 0
while min(want.values()) < 6:
    nos = "".join(rnd.choice(ALPHA37) for _ in range(6))
    r = suma(nos) % 11
    if r in want and want[r] < 6:
        want[r] += 1
        for reply in "CV":
            m09.append(nos + str(rnd.randrange(10)) + reply)
for nos in ("000000", "ZZZZZZ", "------", "A00000", "00000-"):
    for reply in "CVX":
        m09.append(nos + "0" + reply)
while len(m09) < 300:
    nos = [rnd.choice(ALPHA37) for _ in range(6)]
    if rnd.random() < 0.1:
        nos[rnd.randrange(6)] = rnd.choice(" abz*/.#")
    nos = "".join(nos)
    reply = rnd.choices("CVNYX", weights=[40, 40, 7, 7, 6])[0]
    digit = rnd.randrange(10)
    if reply == "V" and rnd.random() < 0.5 and suma(nos):
        a = 11 - suma(nos) % 11
        digit = a % 10 if a < 10 else (0 if a == 10 else 1)
    m09.append(nos + str(digit) + reply)
cases += ["09|" + c for c in m09[:300]]

# ---- maps04: date check (parse) and date unpack ---------------------------------------------
parse = []
for d in ("05/03/2026", "29/02/2028", "29/02/2000", "29/02/1900", "29/02/2100", "31/04/2026",
          "31/12/9999", "01/01/1601", "31/12/1600", "01/01/0001", "00/05/2026", "05/00/2026",
          "32/01/2026", "05/13/2026", "31/01/2026", "30/02/2026", "28/02/2026", "01/01/2026",
          "5/3/2026  ", "05/03/26  ", "05/03/ 2026", "05/03/2026 ", " 5/03/2026", "05/03/20x6",
          "ab/cd/efgh", "          ", "05/03/2026", "00/00/0000", "99/99/9999", "05//2026  ",
          "05/03/2026"[:9] + "/", "05/03/-026", "05/03/+026", "05/03/2.26"):
    parse.append((d.ljust(10)[:10], 0))
for sep in "./,-":                        # the four delimiters the COBOL normalises to "/"
    parse.append(("05%s03%s2026" % (sep, sep), 0))
    parse.append(("05%s03/2026" % sep, 0))
    parse.append(("05/03%s2026" % sep, 0))
parse += [("05:03:2026", 0), ("05 03 2026", 0), ("05x03/2026", 0), ("05/03x2026", 0),
          ("12x05/20/6", 0), ("12x05/20/x", 0), ("12/05/20/6", 0), ("12/05/20x6", 0),
          ("01/01/16" + "0/", 0), ("0//01/2026", 0)]
for y in (1600, 1601, 1900, 1999, 2000, 2024, 2026, 2100, 2400, 9999, 1, 99, 100):  # years incl. bad
    for m, d in ((1, 1), (2, 29), (2, 28), (12, 31), (4, 30), (4, 31)):
        parse.append(("%02d/%02d/%04d" % (d, m, y), 0))
for _ in range(220):                      # mostly-valid dates with one random corruption
    d, m, y = rnd.randint(1, 31), rnd.randint(1, 12), rnd.randint(1500, 2200)
    s = list("%02d/%02d/%04d" % (d, m, y))
    if rnd.random() < 0.5:
        s[rnd.choice((0, 1, 3, 4, 6, 7, 8, 9))] = rnd.choice(PRINTABLE)
    if rnd.random() < 0.2:
        s[rnd.choice((2, 5))] = rnd.choice("./,-x ")
    parse.append(("".join(s), 0))
for _ in range(60):                       # pure garbage with exactly two slashes
    s = [rnd.choice(PRINTABLE) for _ in range(10)]
    for i in rnd.sample(range(10), 2):
        s[i] = "/"
    parse.append(("".join(s), 0))
for d in ("05/03/2026", "31/02/2026", "xx/xx/xxxx"):   # a negative a-bin still means "parse"
    parse.append((d, -1))
    parse.append((d, -2147483647))
cases += ["04|%s|%s" % (d, b(n)) for d, n in parse]
unpack = [1, 2, 59, 60, 61, 365, 366, 367, 36524, 36525, 73050, 73051, 3067670, 3067671,
          3067672, 3067673, 4000000, 99999999, 2147483647, 146097, 146096, 146098, 44000, 46300]
unpack += [rnd.randint(1, 3067671) for _ in range(90)]
unpack += [rnd.randint(3067672, 2147483647) for _ in range(10)]
for n in unpack:                          # the date text is ignored when a-bin > 0
    cases.append("04|%s|%s" % (rnd.choice(("05/03/2026", "          ", "xx/xx/xxxx")), b(n)))
for n in (0, 1, 3067671):                 # and round trips: parse then unpack-able values
    cases.append("04|%s|%s" % ("01/01/1601", b(n)))

# ---- maps01: password / name encoder (state survives between calls) ------------------------
UP = "CKQUAELSMWYIZJRPBXFVGNODTH"
words = ["ABCD", "abcd", "AbCd", "ZZZZ", "zzzz", "A1B2", "1234", "    ", "A   ", "   Z", "a-b_", "HELP",
         "CKQU", "q.w!", "TeSt", "pass", "WORD", "Wo d", "~~~~", "AAAA", "BBBB", "MIXd"]
names = ["Gilles Youmto", "ACAS Workshop Test Co", "A", "abcdefghijklmnopqrstuvwxyz", "ABCDEFGHIJKLMNOPQRSTUVWXYZ",
         "1234567890", "", "ZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZ", "zzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzz",
         "Hello, World! 123 ?", "THE QUICK BROWN FOX JUMPS OVER", "the quick brown fox jumps over",
         "A1B2C3D4E5F6G7H8I9J0K1L2M3N4O5P6", "!@#$%^&*()_+-=[]{};':,.<>/?", "x" * 31, "x" * 32, "Y" * 32]
for w in words:
    cases.append("01|P" + w.ljust(4)[:4] + " " * 32)
for n in names:
    cases.append("01|N" + " " * 4 + n.ljust(32)[:32])
for _ in range(150):                      # random mixes; digits and punctuation expose the retained buffer
    kind = rnd.choice("PNPNX")
    pool = rnd.choice((UP, UP.lower(), UP + UP.lower(), UP + "0123456789 .-", "".join(PRINTABLE)))
    pw = "".join(rnd.choice(pool) for _ in range(4))
    nm = "".join(rnd.choice(pool) for _ in range(rnd.randint(1, 32))).ljust(32)
    cases.append("01|" + kind + pw + nm)
cases.append("01|P" + "!!!!" + " " * 32)      # a password of non-letters straight after letters
cases.append("01|N" + " " * 4 + "!" * 32)

rnd.shuffle(cases)                         # order matters for maps01 (state), so the shuffle is part of the data
with open(os.path.join(HERE, "maps-cases.txt"), "w", newline="\n", encoding="latin-1") as f:
    f.write("\n".join(cases) + "\n")
by = {k: sum(c.startswith(k + "|") for c in cases) for k in ("01", "04", "09")}
print("wrote maps-cases.txt:", by, "total", len(cases))
